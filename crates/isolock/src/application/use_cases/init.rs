//! Scaffold a minimal, valid starting point: typed configuration and a pinned template.
//!
//! Nothing here invents a pin. A digest identifies bytes a reviewer holds, so a generated
//! digest would be a placeholder, and ISO-32 exists precisely so that placeholders cannot
//! pass the gates. The template therefore carries only those fields whose *shape* is known
//! before review, and names the rest as instructions.

use isolock_cas::Sha256Digest;
use std::fmt::Write as _;
use std::path::Path;

/// The configuration file a project is expected to carry.
pub(crate) const CONFIG_FILE: &str = "isolock.toml";
/// The reviewed manifest `ingest` reads by default.
pub(crate) const MANIFEST_FILE: &str = "isolock.ingest.json";

/// What `init` wrote, in the operator's terms.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct InitOutcome {
    /// Project-relative paths, in the order they were written.
    pub written: Vec<String>,
    /// Paths that already existed and were therefore left untouched.
    pub existing: Vec<String>,
}

/// The running binary, which is the one artifact a project always has real bytes for.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SeedPin {
    /// The digest of this executable.
    pub digest: Sha256Digest,
    /// A `file://` locator for the same bytes, so the pin names where they came from.
    pub source: String,
    /// The basename the artifact is addressed by.
    pub filename: String,
}

impl SeedPin {
    /// Pins the executable that is running, if its bytes are reachable.
    ///
    /// # Errors
    /// Returns a message when the executable path or its bytes are unavailable.
    pub fn current() -> Result<Self, String> {
        let executable = std::env::current_exe()
            .map_err(|error| format!("cannot locate the running isolock executable: {error}"))?;
        Self::from_path(&executable)
    }

    /// Pins the executable at `path`.
    ///
    /// # Errors
    /// Returns a message when the file has no basename or its bytes are unreadable.
    pub fn from_path(path: &Path) -> Result<Self, String> {
        let filename = path
            .file_name()
            .map(|name| name.to_string_lossy().into_owned())
            .ok_or_else(|| "the running isolock executable has no filename".to_owned())?;
        let bytes = std::fs::read(path)
            .map_err(|error| format!("cannot read the running isolock executable: {error}"))?;
        Ok(Self {
            digest: Sha256Digest::from_bytes(&bytes),
            source: format!("file://{}", path.display()),
            filename,
        })
    }
}

/// Writes the starting configuration and a manifest template.
///
/// # Errors
/// Returns a message when the project directory is unusable, a target exists and `force`
/// is not set, or a file cannot be written.
pub fn init_project(
    root: &Path,
    force: bool,
    profile: &str,
    platform: &str,
    seed: &SeedPin,
) -> Result<InitOutcome, String> {
    let targets = [
        (CONFIG_FILE, configuration(profile, platform, seed)),
        (MANIFEST_FILE, manifest()),
    ];
    let mut outcome = InitOutcome {
        written: Vec::new(),
        existing: Vec::new(),
    };
    for (name, contents) in targets {
        let path = root.join(name);
        if path.exists() && !force {
            outcome.existing.push(name.to_owned());
            continue;
        }
        std::fs::write(&path, contents).map_err(|error| format!("cannot write {name}: {error}"))?;
        outcome.written.push(name.to_owned());
    }
    // Refusing is a decision, not a crash: report every conflicting path at once so the
    // operator does not discover them one flag at a time.
    if !outcome.existing.is_empty() {
        return Err(format!(
            "refusing to overwrite existing {} (pass --force to replace)",
            outcome.existing.join(", ")
        ));
    }
    Ok(outcome)
}

/// A minimal configuration that validates immediately and fails only for missing pins.
///
/// The seed carries a real digest for *this binary*, which `init` can compute because the
/// bytes are on disk. Every other pin is absent rather than guessed.
fn configuration(profile: &str, platform: &str, seed: &SeedPin) -> String {
    let mut text = String::new();
    let _ = writeln!(
        text,
        "# Generated by Isolock. Review every pin before relying on it.\n\
         schema-version = 1\n\n\
         [storage]\n\
         cas-dir = \".isolock/cas\"\n\n\
         [profiles.{profile}]\n\
         provider = \"standalone\"\n\
         platforms = [\"{platform}\"]\n"
    );
    // The seed is the one pin `init` can state truthfully: the digest is computed over
    // this binary's own bytes, which are on disk right now. Everything else is absent.
    let _ = writeln!(
        text,
        "\n[profiles.{profile}.platform-tools.{platform}.seeds.isolock]\n\
         version = \"{}\"\n\
         platform = \"{platform}\"\n\
         digest = \"{}\"\n\
         filename = \"{}\"\n\
         source = \"{}\"\n\
         # A plain executable needs no archive entry. Change this if you pin an archive\n\
         # and add the executable path inside it.\n\
         format = \"raw\"\n",
        env!("CARGO_PKG_VERSION"),
        seed.digest.as_str(),
        seed.filename,
        seed.source
    );
    text
}

/// The manifest template: shape, never values.
fn manifest() -> String {
    r#"{
  "schema-version": 1,
  "artifacts": []
}
"#
    .to_owned()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_seed_pin_describes_the_bytes_at_its_path() {
        let temp = tempfile::tempdir().unwrap();
        let path = temp.path().join("isolock");
        std::fs::write(&path, b"reviewed bytes").unwrap();
        let pin = SeedPin::from_path(&path).unwrap();
        assert_eq!(pin.digest, Sha256Digest::from_bytes(b"reviewed bytes"));
        assert_eq!(pin.filename, "isolock");
        assert_eq!(pin.source, format!("file://{}", path.display()));
    }

    #[test]
    fn a_path_without_a_basename_is_refused() {
        let error = SeedPin::from_path(Path::new("/")).unwrap_err();
        assert!(error.contains("has no filename"), "{error}");
    }

    #[test]
    fn an_unreadable_executable_is_reported_rather_than_guessed() {
        let temp = tempfile::tempdir().unwrap();
        let missing = temp.path().join("absent");
        let error = SeedPin::from_path(&missing).unwrap_err();
        assert!(
            error.contains("cannot read the running isolock executable"),
            "{error}"
        );
    }
}
