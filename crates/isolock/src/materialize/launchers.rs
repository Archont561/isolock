//! Generated wrappers are convenience boundaries, not an OS or network sandbox.

use super::{archive, executable, payloads, seeds, Derived};
use crate::profile_store::{self, Workspace};
use isolock_plan::profile::{ArtifactKind, ProfileManifest, Provider};
use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

#[derive(Clone, Copy)]
pub(super) struct Paths<'a> {
    pub stage: &'a Path,
    pub destination: &'a Path,
}

pub(super) fn create(
    workspace: &Workspace,
    manifest: &ProfileManifest,
    derived: &Derived,
    paths: Paths<'_>,
    prefixes: &BTreeMap<String, PathBuf>,
) -> Result<(), String> {
    let Paths { stage, destination } = paths;
    let bin = stage.join("bin");
    fs::create_dir_all(&bin).map_err(|error| error.to_string())?;
    let mut environment = environment(workspace, manifest, derived, stage, destination)?;
    if manifest.specification.provider == Provider::Composed {
        composed_bins(&bin, prefixes, manifest)?;
    } else {
        seeds::launcher(
            &bin.join("isolock"),
            derived
                .seeds
                .get("isolock")
                .ok_or("verified Isolock seed is missing")?,
            &BTreeMap::new(),
        )?;
        if let Some(pixi) = derived.seeds.get("pixi") {
            seeds::launcher(&bin.join("pixi"), pixi, &BTreeMap::new())?;
        }
        rust_bins(&bin, derived, manifest, &mut environment)?;
        python_bins(workspace, manifest, derived, paths, &environment)?;
        javascript_bins(&bin, derived, manifest, destination, &environment)?;
    }
    let activation = format!(
        "# Generated by Isolock. Source this file.\nexport PATH={}:\"$PATH\"\n",
        payloads::quote(&destination.join("bin"))
    );
    profile_store::write_file(&stage.join("activate"), activation.as_bytes(), true)
}

fn environment(
    workspace: &Workspace,
    manifest: &ProfileManifest,
    derived: &Derived,
    stage: &Path,
    destination: &Path,
) -> Result<BTreeMap<String, String>, String> {
    let mut environment = BTreeMap::new();
    let mut path = vec![destination.join("bin")];
    // Toolchain support executables (for example a bundled linker) belong to the
    // same verified runtime prefix, not an unrelated environment on the host PATH.
    for prefix in derived.runtimes.values().chain(derived.pixi_prefix.iter()) {
        if prefix.is_dir() {
            path.push(prefix.join("bin"));
        }
    }
    if let Some(javascript) = &derived.javascript {
        path.push(javascript.join("node_modules/.bin"));
    }
    environment.insert(
        "PATH".into(),
        path.iter()
            .map(|path| path.to_string_lossy())
            .collect::<Vec<_>>()
            .join(":")
            + ":/usr/bin:/bin",
    );
    if let Some(cargo) = &derived.cargo {
        payloads::cargo_config(&stage.join("cargo-home"), cargo, &manifest.artifacts)?;
        environment.insert(
            "CARGO_HOME".into(),
            destination
                .join("cargo-home")
                .to_string_lossy()
                .into_owned(),
        );
        environment.insert("CARGO_NET_OFFLINE".into(), "true".into());
    }
    if let Some(wheels) = &derived.wheels {
        environment.insert("PIP_NO_INDEX".into(), "1".into());
        environment.insert(
            "PIP_FIND_LINKS".into(),
            wheels.to_string_lossy().into_owned(),
        );
        environment.insert("PIP_REQUIRE_HASHES".into(), "1".into());
        environment.insert("PIP_CONFIG_FILE".into(), "/dev/null".into());
        environment.insert("PIP_DISABLE_PIP_VERSION_CHECK".into(), "1".into());
    }
    if let Some(javascript) = &derived.javascript {
        environment.insert(
            "NODE_PATH".into(),
            javascript
                .join("node_modules")
                .to_string_lossy()
                .into_owned(),
        );
    }
    environment.insert(
        "PYTHONPATH".into(),
        workspace
            .root
            .join(".isolock/python-sites")
            .join(manifest.digest()?.as_str())
            .to_string_lossy()
            .into_owned(),
    );
    environment.insert("PYTHONNOUSERSITE".into(), "1".into());
    environment.insert("PYTHONDONTWRITEBYTECODE".into(), "1".into());
    Ok(environment)
}

fn rust_bins(
    bin: &Path,
    derived: &Derived,
    manifest: &ProfileManifest,
    environment: &mut BTreeMap<String, String>,
) -> Result<(), String> {
    if let Some(rust) = derived
        .runtimes
        .get("rust")
        .or(derived.pixi_prefix.as_ref())
    {
        if derived.runtimes.contains_key("rust") || manifest.specification.cargo_lock.is_some() {
            environment.insert(
                "RUSTC".into(),
                executable(rust, "rustc")?.to_string_lossy().into_owned(),
            );
            for name in ["cargo", "rustc"] {
                seeds::launcher(&bin.join(name), &executable(rust, name)?, environment)?;
            }
        }
    }
    Ok(())
}

fn python_bins(
    workspace: &Workspace,
    manifest: &ProfileManifest,
    derived: &Derived,
    paths: Paths<'_>,
    environment: &BTreeMap<String, String>,
) -> Result<(), String> {
    let Paths { stage, destination } = paths;
    let Some(python) = derived
        .runtimes
        .get("python")
        .or(derived.pixi_prefix.as_ref())
    else {
        return Ok(());
    };
    if !derived.runtimes.contains_key("python")
        && !manifest
            .artifacts
            .iter()
            .any(|artifact| artifact.kind == ArtifactKind::Conda && artifact.name == "python")
    {
        return Ok(());
    }
    let python = executable(python, "python")?;
    seeds::launcher(&stage.join("bin/python"), &python, environment)?;
    let script = format!("#!/bin/sh\ncase \"${{1:-}}\" in\n --version) exec {} -I -m pip --version ;;\n install) [ \"$#\" -eq 1 ] || {{ echo 'isolock pip: install consumes the locked requirements only' >&2; exit 1; }} ;;\n *) echo 'isolock pip: use install (no extra arguments) or --version' >&2; exit 1 ;;\nesac\nexec {} -I -m pip --isolated install --no-index --no-deps --require-hashes --no-compile --find-links {} --target {} -r {}\n", payloads::quote(&python), payloads::quote(&python), payloads::quote(derived.wheels.as_deref().ok_or("Python profiles require a locked wheelhouse")?), payloads::quote(&workspace.root.join(".isolock/python-sites").join(manifest.digest()?.as_str())), payloads::quote(&destination.join("requirements.txt")));
    script_file(&stage.join("bin/pip"), &script)?;
    let requirements = manifest
        .artifacts
        .iter()
        .filter(|artifact| artifact.kind == ArtifactKind::Wheel)
        .map(|artifact| {
            format!(
                "{}=={} --hash=sha256:{}\n",
                artifact.name,
                artifact.version,
                artifact.digest.as_str()
            )
        })
        .collect::<String>();
    profile_store::write_file(
        &stage.join("requirements.txt"),
        requirements.as_bytes(),
        true,
    )
}

fn javascript_bins(
    bin: &Path,
    derived: &Derived,
    manifest: &ProfileManifest,
    destination: &Path,
    environment: &BTreeMap<String, String>,
) -> Result<(), String> {
    for name in ["node", "bun"] {
        let conda = derived.pixi_prefix.as_ref().filter(|_| {
            manifest.artifacts.iter().any(|artifact| {
                artifact.kind == ArtifactKind::Conda
                    && (artifact.name == name || (name == "node" && artifact.name == "nodejs"))
            })
        });
        if let Some(runtime) = derived.runtimes.get(name).or(conda) {
            let executable = if runtime.is_file() {
                runtime.clone()
            } else {
                executable(runtime, name)?
            };
            if name == "bun" {
                bun_launcher(
                    &bin.join("bun"),
                    &executable,
                    derived.javascript.as_deref(),
                    environment,
                )?;
                script_file(
                    &bin.join("bunx"),
                    &format!(
                        "#!/bin/sh\nexec {} x \"$@\"\n",
                        payloads::quote(&destination.join("bin/bun"))
                    ),
                )?;
            } else {
                seeds::launcher(&bin.join(name), &executable, environment)?;
            }
        }
    }
    Ok(())
}

fn script_file(path: &Path, script: &str) -> Result<(), String> {
    profile_store::write_file(path, script.as_bytes(), true)?;
    archive::executable(path)
}

fn bun_launcher(
    path: &Path,
    runtime: &Path,
    javascript: Option<&Path>,
    environment: &BTreeMap<String, String>,
) -> Result<(), String> {
    let mut script = String::from("#!/bin/sh\n");
    for (name, value) in environment {
        let _ = writeln!(script, "export {name}={}", payloads::quote_string(value));
    }
    let bins = javascript.map_or_else(
        || PathBuf::from("/nonexistent-isolock-bin"),
        |path| path.join("node_modules/.bin"),
    );
    let _ = writeln!(script, "case \"${{1:-}}\" in\n x|exec) shift; name=${{1:-}}; case \"$name\" in ''|*[!A-Za-z0-9._-]*) echo 'isolock bun x: expected a restored executable name' >&2; exit 1;; esac; shift; [ -f {}/\"$name\" ] || {{ echo 'isolock bun x: package is not in the locked profile' >&2; exit 1; }}; exec {}/\"$name\" \"$@\" ;;\n add|install|update|create|remove|link|unlink|pm) echo 'isolock bun: package resolution is disabled; update the profile lock instead' >&2; exit 1 ;;\nesac\nexec {} --no-install \"$@\"", payloads::quote(&bins), payloads::quote(&bins), payloads::quote(runtime));
    script_file(path, &script)
}

fn composed_bins(
    bin: &Path,
    prefixes: &BTreeMap<String, PathBuf>,
    manifest: &ProfileManifest,
) -> Result<(), String> {
    for name in manifest.constituents.keys() {
        let prefix = prefixes
            .get(name)
            .ok_or("constituent was not materialized")?;
        for entry in fs::read_dir(prefix.join("bin")).map_err(|error| error.to_string())? {
            let entry = entry.map_err(|error| error.to_string())?;
            let destination = bin.join(entry.file_name());
            if destination.exists() {
                // Isolock is the shared seed; other capabilities must be selected unambiguously.
                if entry.file_name() == "isolock" {
                    continue;
                }
                return Err("composed profiles expose conflicting executable names".into());
            }
            seeds::launcher(&destination, &entry.path(), &BTreeMap::new())?;
        }
    }
    Ok(())
}
